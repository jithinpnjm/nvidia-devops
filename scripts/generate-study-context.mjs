import fs from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const docsDir = path.join(root, 'docs');
const outputPath = path.join(root, 'src', 'data', 'chapterStudyContexts.ts');
const volumeLens = {
  '01': 'Linux processes, memory, storage, networking, containers, systemd, and host-level evidence',
  '02': 'production Python design, testing, APIs, concurrency, subprocess safety, observability, and automation',
  '03': 'Kubernetes control-plane mechanics, scheduling, kubelet/CRI, networking, storage, security, autoscaling, operators, and upgrades',
  '04': 'GPU execution, memory and topology, drivers/CUDA, device plugins, GPU Operator, sharing, telemetry, and fleet health',
  '05': 'training and inference workload mechanics, model serving, KV cache, autoscaling, RAG, security, performance, and benchmarking',
  '06': 'distributed systems, Ethernet/InfiniBand/RoCE, RDMA, NCCL, GPUDirect, storage pipelines, Slurm, and topology-aware scheduling',
  '07': 'metrics/logs/traces, SLOs, Prometheus, GPU and inference observability, incident response, alerting, and reliability testing',
  '08': 'customer discovery, architecture trade-offs, Kubernetes versus Slurm, capacity/TCO, PoCs, security, migration, and executive communication',
  '09': 'senior interview reasoning across Python, Linux, Kubernetes, GPUs, AI inference, networking, architecture, discovery, and stakeholder scenarios',
};

async function markdownFiles(directory) {
  const entries = await fs.readdir(directory, {withFileTypes: true});
  const nested = await Promise.all(entries.map((entry) => {
    const target = path.join(directory, entry.name);
    return entry.isDirectory() ? markdownFiles(target) : target.endsWith('.md') ? [target] : [];
  }));
  return nested.flat().sort();
}

const clean = (value) => value
  .replace(/[`*_>#|]/g, ' ')
  .replace(/\[(.*?)\]\([^)]*\)/g, '$1')
  .replace(/\s+/g, ' ')
  .trim();

const yamlField = (frontmatter, name) => {
  const match = frontmatter.match(new RegExp(`^${name}:\\s*[\"']?(.+?)[\"']?\\s*$`, 'm'));
  return match ? match[1].replace(/[\"']$/, '').trim() : '';
};

const files = await markdownFiles(docsDir);
const contexts = {};

for (const file of files) {
  const markdown = await fs.readFile(file, 'utf8');
  const frontmatter = markdown.match(/^---\n([\s\S]*?)\n---/)?.[1] || '';
  const title = yamlField(frontmatter, 'title');
  if (!title) continue;
  const relative = path.relative(docsDir, file);
  const volume = relative.match(/^volume-(\d{2})/)?.[1] || 'intro';
  const learningOutcome = clean(
    markdown.match(/\*\*Learning outcome:\*\*\s*(.+)/i)?.[1]
      || markdown.match(/^##\s+(?:Learning outcomes?|Objective)\s*\n+([^#\n].+)/im)?.[1]
      || yamlField(frontmatter, 'description'),
  );
  const headings = [...markdown.matchAll(/^#{1,3}\s+(.+)$/gm)]
    .map((match) => clean(match[1]))
    .filter((heading) => heading && !/^sources|references|further reading$/i.test(heading))
    .filter((heading, index, all) => all.indexOf(heading) === index)
    .slice(0, 14);
  const codeLanguages = [...markdown.matchAll(/^```([a-zA-Z0-9_+-]*)/gm)]
    .map((match) => match[1] || 'text')
    .filter((language, index, all) => all.indexOf(language) === index)
    .slice(0, 6);
  contexts[title] = {
    volume: volume === 'intro' ? 'Academy orientation' : `Volume ${Number(volume)}`,
    lens: volumeLens[volume] || 'cross-volume senior DevOps and AI-infrastructure practice',
    learningOutcome,
    sections: headings,
    codeLanguages,
  };
}

const output = `// Generated by scripts/generate-study-context.mjs. Do not edit by hand.
export type ChapterStudyContext = {
  volume: string;
  lens: string;
  learningOutcome: string;
  sections: string[];
  codeLanguages: string[];
};

export const chapterStudyContexts: Record<string, ChapterStudyContext> = ${JSON.stringify(contexts, null, 2)};
`;

await fs.mkdir(path.dirname(outputPath), {recursive: true});
await fs.writeFile(outputPath, output);
console.log(`Generated chapter-specific study context for ${Object.keys(contexts).length} documents.`);
